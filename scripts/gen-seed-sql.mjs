// Writes supabase/seed.sql from src/data/seed.json.
// Re-running it is safe: existing rows are left alone unless you pass --overwrite.
import { readFileSync, writeFileSync } from 'node:fs';
const seed = JSON.parse(readFileSync(new URL('../src/data/seed.json', import.meta.url), 'utf8'));
const overwrite = process.argv.includes('--overwrite');
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
let sql = '-- Generated by scripts/gen-seed-sql.mjs — starting data for the Bandon Shoe app\n';
for (const [table, rows] of Object.entries(seed)) {
  for (const row of rows) {
    sql += `insert into public.${table} (id, data) values (${q(row.id)}, ${q(JSON.stringify(row))}::jsonb) on conflict (id) do ${overwrite ? 'update set data = excluded.data' : 'nothing'};\n`;
  }
}
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log('supabase/seed.sql written', overwrite ? '(overwrite mode)' : '');
