// The group doesn't play these, so they are left out of the app.
const DROP_TEES = ['Orange', 'Royal Blue'];

export function applyScorecard(course) {
  const sc = SCORECARDS[course.id];
  if (!sc) return course;
  const keep = sc.tees.map((t, j) => [t, j]).filter(([t]) => !DROP_TEES.includes(t.name));
  const tees = keep.map(([t], i) => ({ ...t, default: t.name === 'Green' || (i === 0 && !keep.some(([x]) => x.name === 'Green')) }));
  const holes = sc.holes.map(([par, si, ...yds], i) => ({
    n: i + 1, par, si, note: '',
    yards: Object.fromEntries(keep.map(([t, j]) => [t.name, yds[j]])),
  }));
  return { ...course, tees, holes, verified: false, source: SOURCE, caveat: sc.caveat || '' };
}
